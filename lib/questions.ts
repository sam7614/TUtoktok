export type RecordData = {date:string;course:string;mentor:string;answers:Record<string,string>;summary:Record<string,string>;extra:Record<string,string>;notes:string;complete:boolean;updatedAt?:number;exported?:{url:string;at:string;fingerprint:string};pending?:string};
export function emptyRecord(course=''):RecordData {return {date:'2026-10-20',course,mentor:'',answers:{},summary:{},extra:{},notes:'',complete:false};}
export function questionKey(s:number,q:number){return `${s}-${q}`;}
export function documentText(professor:string,stage:number,r:RecordData){
 const lines=[`찾아가는 교수법 똑-똑 | ${stages[stage]}`,`${professor} 교수님`, `상담일: ${r.date || '미기재'}`,`교과목: ${r.course || '미기재'}`,`멘토: ${r.mentor || '미기재'}`,`기록 상태: ${r.complete ? '작성 완료' : '작성 중'}`,''];
 sections[stage].forEach((s,i)=>{lines.push(`${i+1}. ${s.title}`,s.purpose,'');s.questions.forEach((q,j)=>lines.push(`질문 ${j+1}. ${q}`,`답변: ${r.answers[questionKey(i,j)]?.trim() || '(미작성)'}`,''));});
 if(stage===0){lines.push('선택 후속 질문','');probes.forEach((p,i)=>p.slice(1).forEach((q,j)=>lines.push(`상황: ${p[0]}`,`질문: ${q}`,`답변: ${r.extra[`${i}-${j}`]?.trim() || '(미작성)'}`,'')));}
 lines.push('상담 요약 및 후속 합의','');summaryLabels.forEach((label,i)=>lines.push(label,r.summary[String(i)]?.trim() || '(미작성)',''));
 lines.push('멘토 메모',r.notes?.trim() || '(미작성)','');return lines.join('\n');
}
